import { readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const webRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);
const fixturesDirectory = path.join(webRoot, "src/mocks/fixtures");
const outputFile = path.join(webRoot, "src/mocks/fixture-modules.ts");

async function listJsonFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = await Promise.all(
    entries
      .sort((left, right) => left.name.localeCompare(right.name))
      .map(async (entry) => {
        const entryPath = path.join(directory, entry.name);
        if (entry.isDirectory()) return listJsonFiles(entryPath);
        return entry.isFile() && entry.name.endsWith(".json") ? [entryPath] : [];
      }),
  );
  return files.flat();
}

const fixtures = await listJsonFiles(fixturesDirectory);
const imports = fixtures.map((file, index) => {
  const relativePath = path.relative(path.dirname(outputFile), file).replaceAll("\\", "/");
  return {
    identifier: `fixture${index}`,
    importPath: `./${relativePath}`,
    key: `./${relativePath}`,
  };
});

const content = [
  "// Generated by scripts/generate-fixture-modules.mjs. Re-run after adding fixtures.",
  ...imports.map(
    ({ identifier, importPath }) =>
      `import ${identifier} from "${importPath}";`,
  ),
  "",
  "export const fixtureModules: Record<string, unknown> = {",
  ...imports.map(
    ({ identifier, key }) => `  "${key}": ${identifier},`,
  ),
  "};",
  "",
].join("\n");

await writeFile(outputFile, content);
